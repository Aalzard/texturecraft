use crate::{FormatError, Result};

/// Mesh files larger than this are refused before reading.
pub const MAX_MESH_FILE_BYTES: u64 = 2 << 30;
/// Vertices accepted from a file.
pub const MAX_VERTICES: usize = 3 * MAX_TRIANGLES;
/// Layout parameters of the automatic unwrap (padding in texels at this resolution).
const UNWRAP_RESOLUTION: u32 = 1024;
const UNWRAP_PADDING: f32 = 4.0;
/// Resolution of the overlap check in the report.
const REPORT_RESOLUTION: u32 = 512;

/// File extensions [`import_mesh_bytes`] understands.
pub const MESH_EXTENSIONS: [&str; 11] = ["gltf", "glb", "fbx", "dae", "usd", "usda", "usdc", "usdz", "obj", "ply", "stl"];

#[derive(Clone, Debug, PartialEq)]
pub struct ImportedMesh {
    pub mesh: Mesh,
    pub report: MeshReport,
}

/// What the importer found and fixed, for the import dialog.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct MeshReport {
    pub triangles: usize,
    pub vertices: usize,
    pub materials: usize,
    /// The file had no UVs; they were generated by the automatic unwrap.
    pub uvs_generated: bool,
    /// Triangles with a UV outside 0..1.
    pub uv_out_of_range: usize,
    /// Overlapping texels / covered texels (512² per material).
    pub overlap_ratio: f32,
    pub zero_area_uv_triangles: usize,
    pub warnings: Vec<String>,
}

/// Geometry as read from a file, before normals, UVs and tangents are completed.
#[derive(Default)]
pub(crate) struct RawMesh {
    pub positions: Vec<Vec3>,
    /// Per-vertex normals for every vertex, or None to compute smooth (welded) normals.
    pub normals: Option<Vec<Vec3>>,
    /// Per-vertex UVs (glTF convention) for every vertex, or None to auto-unwrap.
    pub uvs: Option<Vec<Vec2>>,
    /// Per-vertex linear RGBA colors for every vertex, or None.
    pub colors: Option<Vec<Vec4>>,
    /// Triangles (vertex indices) per (material, part name); an empty part is unnamed.
    pub groups: Vec<(String, String, Vec<u32>)>,
    pub warnings: Vec<String>,
}

impl RawMesh {
    /// Triangle list of `material` in `part`, created on first use.
    pub fn group(&mut self, material: &str, part: &str) -> &mut Vec<u32> {
        let i = match self.groups.iter().position(|(m, p, _)| m == material && p == part) {
            Some(i) => i,
            None => {
                self.groups.push((material.to_string(), part.to_string(), Vec::new()));
                self.groups.len() - 1
            }
        };
        &mut self.groups[i].2
    }

    pub fn triangle_count(&self) -> usize {
        self.groups.iter().map(|(_, _, g)| g.len() / 3).sum()
    }
}

/// One polygon corner of a scene format (FBX, COLLADA), already in world space.
#[derive(Clone, Copy)]
pub(crate) struct Corner {
    pub p: Vec3,
    pub n: Option<Vec3>,
    pub uv: Option<Vec2>,
}

/// Collects polygons into a [`RawMesh`]: fan triangulation, one vertex per unique corner, and
/// normals / UVs kept only when every corner has them (else computed / unwrapped).
#[derive(Default)]
pub(crate) struct PolygonSink {
    /// Part name of the polygons that follow.
    pub part: String,
    raw: RawMesh,
    normals: Vec<Vec3>,
    uvs: Vec<Vec2>,
    missing_normals: bool,
    missing_uvs: bool,
    some_uvs: bool,
    ids: HashMap<[u32; 8], u32>,
    polygon: Vec<u32>,
    triangles: usize,
}

impl PolygonSink {
    pub fn polygon(&mut self, material: &str, corners: &[Corner]) -> Result<()> {
        if corners.len() < 3 {
            return Ok(());
        }
        check_triangles(self.triangles, corners.len() - 2)?;
        self.triangles += corners.len() - 2;
        self.polygon.clear();
        for c in corners {
            self.missing_normals |= c.n.is_none();
            self.missing_uvs |= c.uv.is_none();
            self.some_uvs |= c.uv.is_some();
            let (n, uv) = (c.n.unwrap_or_default(), c.uv.unwrap_or_default());
            let key = [c.p.x, c.p.y, c.p.z, n.x, n.y, n.z, uv.x, uv.y].map(f32::to_bits);
            let id = match self.ids.entry(key) {
                Entry::Occupied(e) => *e.get(),
                Entry::Vacant(e) => {
                    let id = self.raw.positions.len();
                    check_vertices(id + 1)?;
                    self.raw.positions.push(c.p);
                    self.normals.push(n);
                    self.uvs.push(uv);
                    *e.insert(id as u32)
                }
            };
            self.polygon.push(id);
        }
        let group = self.raw.group(material, &self.part);
        let (first, rest) = self.polygon.split_first().unwrap_or((&0, &[]));
        for w in rest.windows(2) {
            group.extend_from_slice(&[*first, w[0], w[1]]);
        }
        Ok(())
    }

    pub fn warn(&mut self, msg: String) {
        if !self.raw.warnings.contains(&msg) {
            self.raw.warnings.push(msg);
        }
    }

    pub fn finish(mut self) -> RawMesh {
        if self.missing_uvs && self.some_uvs {
            self.warn("some polygons have no UVs; the whole mesh was unwrapped automatically".into());
        }
        self.raw.normals = (!self.missing_normals).then_some(self.normals);
        self.raw.uvs = (!self.missing_uvs).then_some(self.uvs);
        self.raw
    }
}

/// Error unless `n` more triangles keep the total within [`MAX_TRIANGLES`].
pub(crate) fn check_triangles(have: usize, more: usize) -> Result<()> {
    if have.saturating_add(more) > MAX_TRIANGLES {
        return Err(FormatError::TooLarge(format!("mesh has more than {MAX_TRIANGLES} triangles")));
    }
    Ok(())
}

pub(crate) fn check_vertices(n: usize) -> Result<()> {
    if n > MAX_VERTICES {
        return Err(FormatError::TooLarge(format!("mesh has more than {MAX_VERTICES} vertices")));
    }
    Ok(())
}

fn extension(file_name: &str) -> String {
    std::path::Path::new(file_name).extension().and_then(|e| e.to_str()).unwrap_or_default().to_ascii_lowercase()
}

/// Import a mesh from bytes; the format comes from `file_name`'s extension. glTF must be GLB or
/// self-contained (data-URI buffers); OBJ material libraries are not read (usemtl names are).
pub fn import_mesh_bytes(file_name: &str, bytes: &[u8]) -> Result<ImportedMesh> {
    finish(read(file_name, bytes, None)?)
}

/// Import a mesh file. A `.gltf` may reference external `.bin` buffers next to it.
#[cfg(not(target_arch = "wasm32"))]
pub fn import_mesh(path: &std::path::Path) -> Result<ImportedMesh> {
    let bytes = crate::read_capped(path, MAX_MESH_FILE_BYTES)?;
    let name = path.file_name().and_then(|n| n.to_str()).unwrap_or_default();
    finish(read(name, &bytes, path.parent())?)
}

/// Import a high-poly (or cage) mesh for baking: like [`import_mesh_bytes`], but missing UVs stay
/// at 0 and no tangents are generated (bakers read positions, normals, colors and part names), so
/// million-triangle meshes import quickly.
pub fn import_high_poly_bytes(file_name: &str, bytes: &[u8]) -> Result<Mesh> {
    let (mut mesh, _, uvs) = geometry(read(file_name, bytes, None)?)?;
    let n = mesh.positions.len();
    mesh.uvs = uvs.filter(|uv| uv.len() == n && uv.iter().all(|v| v.is_finite())).unwrap_or_else(|| vec![Vec2::ZERO; n]);
    mesh.tangents = vec![Vec4::new(1.0, 0.0, 0.0, 1.0); n];
    mesh.validate()?;
    Ok(mesh)
}

fn read(file_name: &str, bytes: &[u8], base: Option<&std::path::Path>) -> Result<RawMesh> {
    let mut raw = match extension(file_name).as_str() {
        "gltf" | "glb" => gltf::read(bytes, base)?,
        "fbx" => fbx::read(bytes)?,
        "dae" => dae::read(bytes)?,
        "usd" | "usda" | "usdc" | "usdz" => usd::read(file_name, bytes)?,
        "obj" => obj::read(bytes)?,
        "ply" => ply::read(bytes)?,
        "stl" => stl::read(bytes)?,
        other => return Err(FormatError::Unsupported(format!("mesh format \".{other}\" (supported: {})", MESH_EXTENSIONS.join(", ")))),
    };
    let stem = std::path::Path::new(file_name).file_stem().and_then(|s| s.to_str()).unwrap_or_default();
    for (material, part, _) in &mut raw.groups {
        if part.is_empty() {
            *part = if stem.is_empty() { material.clone() } else { stem.to_string() };
        }
    }
    Ok(raw)
}

/// Positions, submeshes (materials contiguous), normals and colors of a raw mesh, validated;
/// plus its warnings and UVs (the mesh's UVs and tangents are left empty).
fn geometry(raw: RawMesh) -> Result<(Mesh, Vec<String>, Option<Vec<Vec2>>)> {
    let RawMesh { positions, normals, uvs, colors, groups, warnings } = raw;
    check_vertices(positions.len())?;
    check_triangles(0, groups.iter().map(|(_, _, g)| g.len() / 3).sum())?;
    let mut mesh = Mesh { positions, ..Mesh::default() };
    let mut groups: Vec<(usize, String, Vec<u32>)> = groups
        .into_iter()
        .filter(|(_, _, g)| g.len() >= 3)
        .map(|(material, part, tris)| {
            let m = mesh.materials.iter().position(|x| *x == material).unwrap_or(mesh.materials.len());
            if m == mesh.materials.len() {
                mesh.materials.push(material);
            }
            (m, part, tris)
        })
        .collect();
    groups.sort_by_key(|g| g.0);
    for (material, name, tris) in groups {
        let start = u32::try_from(mesh.indices.len()).map_err(|_| FormatError::TooLarge("index count".into()))?;
        let count = (tris.len() / 3 * 3) as u32;
        mesh.indices.extend_from_slice(tris.get(..count as usize).unwrap_or_default());
        mesh.submeshes.push(SubMesh { name, material, start, count });
    }
    if mesh.indices.is_empty() {
        return Err(FormatError::Invalid("the file contains no triangles".into()));
    }
    if let Some(bad) = mesh.indices.iter().find(|i| **i as usize >= mesh.positions.len()) {
        return Err(FormatError::Invalid(format!("vertex index {bad} out of range ({} vertices)", mesh.positions.len())));
    }
    if mesh.positions.iter().any(|p| !p.is_finite()) {
        return Err(FormatError::Invalid("the mesh has non-finite vertex positions".into()));
    }
    if all_triangles_degenerate(&mesh) {
        return Err(FormatError::Invalid("every triangle of the mesh is degenerate (zero area)".into()));
    }
    mesh.normals = match normals {
        Some(n) if n.len() == mesh.positions.len() => n.into_iter().map(|v| v.try_normalize().unwrap_or(Vec3::Y)).collect(),
        _ => smooth_normals(&mesh),
    };
    if let Some(c) = colors.filter(|c| c.len() == mesh.positions.len()) {
        mesh.colors = c.into_iter().map(|v| if v.is_finite() { v.clamp(Vec4::ZERO, Vec4::ONE) } else { Vec4::ONE }).collect();
    }
    Ok((mesh, warnings, uvs))
}

/// Complete a raw mesh: submeshes, normals, UVs, tangents, validation and the report.
pub(crate) fn finish(raw: RawMesh) -> Result<ImportedMesh> {
    let (mut mesh, mut warnings, uvs) = geometry(raw)?;
    let uvs_generated = match uvs {
        Some(uv) if uv.len() == mesh.positions.len() => {
            if uv.iter().any(|v| !v.is_finite()) {
                warnings.push("non-finite UVs were replaced with 0".into());
            }
            mesh.uvs = uv.into_iter().map(|v| if v.is_finite() { v } else { Vec2::ZERO }).collect();
            mesh.compute_tangents();
            false
        }
        _ => {
            let charts = auto_unwrap(&mut mesh, UNWRAP_PADDING, UNWRAP_RESOLUTION)?;
            warnings.push(format!("the mesh has no UVs; generated an automatic unwrap with {charts} charts"));
            true
        }
    };
    mesh.validate()?;
    let report = report(&mesh, uvs_generated, warnings);
    Ok(ImportedMesh { mesh, report })
}

/// Area-weighted smooth normals over welded positions (UV seams do not split shading).
fn smooth_normals(mesh: &Mesh) -> Vec<Vec3> {
    let weld = weld_ids(&mesh.positions);
    let mut acc = vec![Vec3::ZERO; mesh.positions.len()];
    for t in mesh.indices.chunks_exact(3) {
        let p = |i: u32| mesh.positions.get(i as usize).copied().unwrap_or_default();
        let face = (p(t[1]) - p(t[0])).cross(p(t[2]) - p(t[0]));
        for v in t {
            if let Some(a) = weld.get(*v as usize).and_then(|w| acc.get_mut(*w as usize)) {
                *a += face;
            }
        }
    }
    weld.iter().map(|w| acc.get(*w as usize).and_then(|n| n.try_normalize()).unwrap_or(Vec3::Y)).collect()
}

fn report(mesh: &Mesh, uvs_generated: bool, mut warnings: Vec<String>) -> MeshReport {
    let (mut out_of_range, mut zero_area) = (0, 0);
    for t in 0..mesh.triangle_count() {
        let Some(vs) = mesh.tri(t) else { continue };
        let uv = vs.map(|v| mesh.uvs.get(v).copied().unwrap_or_default());
        if uv.iter().any(|u| u.min_element() < -1e-4 || u.max_element() > 1.0 + 1e-4) {
            out_of_range += 1;
        }
        if (uv[1] - uv[0]).perp_dot(uv[2] - uv[0]).abs() < 1e-12 {
            zero_area += 1;
        }
    }
    let (mut overlaps, mut covered) = (0u64, 0u64);
    for m in 0..mesh.materials.len() {
        let g = UvGBuffer::new(mesh, m, REPORT_RESOLUTION, REPORT_RESOLUTION);
        overlaps += g.overlaps as u64;
        covered += g.covered_count() as u64;
    }
    let overlap_ratio = if covered == 0 { 0.0 } else { overlaps as f32 / covered as f32 };
    if out_of_range > 0 {
        warnings.push(format!("{out_of_range} triangles have UVs outside 0..1 (painted as UDIM tiles when they lie in tiles 1001 and up)"));
    }
    if overlap_ratio > 0.01 {
        warnings.push(format!("{:.1}% of the UV layout overlaps; painting there affects several places at once", overlap_ratio * 100.0));
    }
    if zero_area > 0 {
        warnings.push(format!("{zero_area} triangles have zero UV area and cannot be painted"));
    }
    MeshReport {
        triangles: mesh.triangle_count(),
        vertices: mesh.vertex_count(),
        materials: mesh.materials.len(),
        uvs_generated,
        uv_out_of_range: out_of_range,
        overlap_ratio,
        zero_area_uv_triangles: zero_area,
        warnings,
    }
}
